def _canonical_json(value: object) -> bytes:
    return (json.dumps(value, ensure_ascii=True, separators=(",", ":"), sort_keys=True) + "\n").encode(
        "utf-8"
    )


def _sha256(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def _identity(stream: DigestStream, ordinal: int) -> str:
    return f"{stream.choose(ADJECTIVES)}_{stream.choose(NOUNS)}_{ordinal:04d}"


def _sentence(stream: DigestStream, ordinal: int) -> str:
    subject = stream.choose(SUBJECTS)
    verb = stream.choose(VERBS)
    obj = stream.choose(OBJECTS)
    condition = stream.choose(CONDITIONS)
    measure = stream.choose(MEASURES)
    pattern = stream.index(5)
    if pattern == 0:
        return f"{subject} {verb} {obj} {condition}."
    if pattern == 1:
        return (
            f"For observation {ordinal}, {subject.lower()} {verb} {obj}; "
            f"the note labels {measure} as simulated rather than measured."
        )
    if pattern == 2:
        return (
            f"Because {measure} can change the interpretation, {subject.lower()} "
            f"{verb} {obj} {condition}."
        )
    if pattern == 3:
        return (
            f"The working record says that {subject.lower()} {verb} {obj}. "
            f"It does so {condition}."
        )
    return (
        f"In a deliberately fictional exercise, {subject.lower()} {verb} {obj} "
        f"{condition}, then marks the {measure} column for a separate reading."
    )


def _prose_block(stream: DigestStream, ordinal: int) -> str:
    title = f"Field memorandum {ordinal:04d}: {_identity(stream, ordinal).replace('_', ' ')}"
    lines = [f"## {title}", ""]
    for paragraph in range(5):
        sentences = [_sentence(stream, ordinal * 20 + paragraph * 4 + item) for item in range(4)]
        lines.extend((" ".join(sentences), ""))
    lines.extend(
        (
            "The examples above are invented for a public benchmark corpus. Names describe",
            "fictional working groups, and numeric readings below are deterministic samples.",
            "",
        )
    )
    return "\n".join(lines)


