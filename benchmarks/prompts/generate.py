class DigestStream:
    """A tiny, explicitly specified deterministic selector stream."""

    def __init__(self, scope: str) -> None:
        self._prefix = f"{SEED}\0{scope}\0".encode("utf-8")
        self._counter = 0

    def index(self, bound: int) -> int:
        if bound <= 0:
            raise ValueError("bound must be positive")
        material = self._prefix + self._counter.to_bytes(8, "big")
        self._counter += 1
        value = int.from_bytes(hashlib.sha256(material).digest()[:8], "big")
        return value % bound

    def choose(self, values: tuple[str, ...]) -> str:
        return values[self.index(len(values))]


