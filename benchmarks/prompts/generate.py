def _json_file(stream: DigestStream, ordinal: int, name: str) -> str:
    rows = []
    for index in range(8):
        rows.append(
            {
                "category": ("calm", "changing", "uncertain")[stream.index(3)],
                "complete": stream.index(5) != 0,
                "reading": 1 + stream.index(999),
                "sequence": index + 1,
                "unit": ("points", "samples", "minutes")[stream.index(3)],
            }
        )
    fixture = {
        "description": "fictional deterministic observation fixture",
        "id": name,
        "rows": rows,
        "schema_version": 1,
    }
    rendered = json.dumps(fixture, ensure_ascii=True, indent=2, sort_keys=True)
    return f"===== FILE: fixtures/{name}.json =====\n{rendered}\n\n"


def _repo_block(stream: DigestStream, ordinal: int) -> str:
    name = _identity(stream, ordinal)
    builders = (
        _python_file,
        _rust_file,
        _typescript_file,
        _toml_file,
        _yaml_file,
        _sql_file,
        _markdown_file,
        _diff_file,
        _json_file,
    )
    return builders[ordinal % len(builders)](stream, ordinal, name)


def _header(spec: ArtifactSpec) -> str:
    return (
        "SYNTHETIC PUBLIC PROMPT CORPUS\n"
        f"Artifact id: {spec.prompt_id}\n"
        f"Byte-size class: {spec.filename.removesuffix('.txt')}\n"
        f"License: {LICENSE_ID}\n"
        f"Source: {SOURCE}\n"
        "Notice: every organization, system, measurement, file, and event below is fictional.\n"
        "Token count: deliberately unmeasured; consult the calibration manifest.\n"
        "\n"
    )


def _short_document(spec: ArtifactSpec) -> bytes:
    stream = DigestStream(spec.prompt_id)
    parts = [_header(spec)]
    ordinal = 0
    byte_count = len(parts[0].encode("utf-8"))
    while byte_count < spec.target_bytes:
        block = _mixed_block(stream, ordinal)
        parts.append(block)
        byte_count += len(block.encode("utf-8"))
        ordinal += 1
    return ("".join(parts).rstrip("\n") + "\n").encode("utf-8")


def _sized_document(spec: ArtifactSpec) -> bytes:
    stream = DigestStream(spec.prompt_id)
    parts = [_header(spec)]
    byte_count = len(parts[0].encode("utf-8"))
    ordinal = 0
    while byte_count < spec.target_bytes:
        if spec.kind == "mixed":
            block = _mixed_block(stream, ordinal)
        elif spec.kind == "repo":
            block = _repo_block(stream, ordinal)
        elif spec.kind == "cold":
            # Alternating whole sections creates a long, heterogeneous cold
            # prompt without tuning or repetitive padding.
            block = (
                _mixed_block(stream, ordinal)
                if ordinal % 5 in (0, 3)
                else _repo_block(stream, ordinal)
            )
        else:
            raise GenerationError(f"unsupported artifact kind: {spec.kind}")
        parts.append(block)
        byte_count += len(block.encode("utf-8"))
        ordinal += 1
    return ("".join(parts).rstrip("\n") + "\n").encode("utf-8")


def _build_outputs() -> tuple[dict[str, bytes], list[dict[str, object]]]:
    if len(ARTIFACT_SPECS) != 7:
        raise GenerationError("the corpus contract requires exactly seven artifacts")
    ids = [spec.prompt_id for spec in ARTIFACT_SPECS]
    filenames = [spec.filename for spec in ARTIFACT_SPECS]
    if len(set(ids)) != len(ids) or len(set(filenames)) != len(filenames):
        raise GenerationError("artifact identifiers and filenames must be unique")

    outputs: dict[str, bytes] = {"LICENSE.txt": LICENSE_TEXT.encode("utf-8")}
    records: list[dict[str, object]] = []
    for spec in ARTIFACT_SPECS:
        content = _short_document(spec) if spec.kind == "short" else _sized_document(spec)
        if len(content) < spec.target_bytes or not content.endswith(b"\n"):
            raise GenerationError(f"generated content invariant failed for {spec.filename}")
        relative_path = f"artifacts/{spec.filename}"
        repository_path = f"{REPOSITORY_PREFIX}/{relative_path}"
        digest = _sha256(content)
        outputs[relative_path] = content
        records.append(
            {
                "bytes": len(content),
                "id": spec.prompt_id,
                "license": LICENSE_ID,
                "path": repository_path,
                "sha256": digest,
                "source": SOURCE,
            }
        )

    provenance = {
        "algorithm": ALGORITHM,
        "artifacts": records,
        "generator": f"{REPOSITORY_PREFIX}/generate.py",
        "generator_version": GENERATOR_VERSION,
        "license": LICENSE_ID,
        "license_file": f"{REPOSITORY_PREFIX}/LICENSE.txt",
        "schema_version": 1,
        "seed": SEED,
        "source": SOURCE,
    }
    manifest = {
        "prompts": [
            {
                "id": record["id"],
                "license": LICENSE_ID,
                "path": record["path"],
                "sha256": record["sha256"],
                "status": "unmeasured",
                "token_count": None,
            }
            for record in records
        ],
        "version": 1,
    }
    outputs["provenance.json"] = _canonical_json(provenance)
    outputs["manifest.json"] = _canonical_json(manifest)
    return outputs, records


def _verify_text_boundaries(outputs: dict[str, bytes]) -> None:
    for relative_path, content in outputs.items():
        if not content.endswith(b"\n") or content.endswith(b"\n\n"):
            raise GenerationError(f"managed output must end in exactly one LF: {relative_path}")
        if any(line.endswith((b" ", b"\t")) for line in content.splitlines()):
            raise GenerationError(f"managed output has trailing whitespace: {relative_path}")


def _reject_unexpected_artifacts(expected_filenames: set[str]) -> None:
    if not ARTIFACT_DIR.exists():
        return
    if not ARTIFACT_DIR.is_dir() or ARTIFACT_DIR.is_symlink():
        raise GenerationError("artifact destination must be a real directory")
    actual = {entry.name for entry in ARTIFACT_DIR.iterdir()}
    unexpected = sorted(actual - expected_filenames)
    if unexpected:
        raise GenerationError(f"refusing unexpected artifact entries: {', '.join(unexpected)}")


def _stage_file(destination: Path, content: bytes) -> Path:
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.is_symlink():
        raise GenerationError(f"refusing symbolic-link destination: {destination.name}")
    handle = tempfile.NamedTemporaryFile(
        mode="wb",
        dir=destination.parent,
        prefix=f".{destination.name}.",
        suffix=".generated",
        delete=False,
    )
    temporary = Path(handle.name)
    try:
        with handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        temporary.chmod(0o644)
        return temporary
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise


def _write_outputs(outputs: dict[str, bytes]) -> None:
    expected_filenames = {spec.filename for spec in ARTIFACT_SPECS}
    _reject_unexpected_artifacts(expected_filenames)
    staged: list[tuple[Path, Path]] = []
    try:
        for relative_path, content in outputs.items():
            destination = BASE_DIR / relative_path
            staged.append((_stage_file(destination, content), destination))
        for temporary, destination in staged:
            os.replace(temporary, destination)
    finally:
        for temporary, _ in staged:
            temporary.unlink(missing_ok=True)


def _verify_outputs(outputs: dict[str, bytes], records: list[dict[str, object]]) -> None:
    expected_filenames = {spec.filename for spec in ARTIFACT_SPECS}
    _reject_unexpected_artifacts(expected_filenames)
    for relative_path, expected in outputs.items():
        path = BASE_DIR / relative_path
        try:
            actual = path.read_bytes()
        except OSError as error:
            raise GenerationError(f"managed output is missing or unreadable: {relative_path}") from error
        if actual != expected:
            raise GenerationError(
                f"managed output diverges: {relative_path}; "
                f"expected sha256={_sha256(expected)}, actual sha256={_sha256(actual)}; "
                "run with --write only when replacement is intentional"
            )

    for record in records:
        path = BASE_DIR.parent.parent / str(record["path"])
        content = path.read_bytes()
        if len(content) != record["bytes"] or _sha256(content) != record["sha256"]:
            raise GenerationError(f"provenance mismatch for {record['id']}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write",
        action="store_true",
        help="explicitly materialize or replace the seven managed artifacts and metadata",
    )
    args = parser.parse_args()

    outputs, records = _build_outputs()
    _verify_text_boundaries(outputs)
    if args.write:
        _write_outputs(outputs)
    _verify_outputs(outputs, records)
    total_bytes = sum(int(record["bytes"]) for record in records)
    action = "generated and verified" if args.write else "verified"
    print(f"{action} {len(records)} deterministic artifacts ({total_bytes} bytes)")
    for record in records:
        print(f"{record['id']}: {record['bytes']} bytes sha256={record['sha256']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
